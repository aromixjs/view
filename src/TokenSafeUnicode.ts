   export function Encode(value: string) {
      const chunks: string[] = [];

      for (const char of value) {
         const codePoint = char.codePointAt(0) as number;

         if (codePoint >= puaBase && codePoint <= puaMax) {
            throw new Error(`Encode: input contains reserved code point U+${codePoint.toString(16)}`);
         }

         const mappedCodePoint = codePointMap.get(codePoint);

         if (mappedCodePoint === undefined) {
            chunks.push(char);
            continue;
         }

         const encodedChar = String.fromCodePoint(mappedCodePoint)
         chunks.push(encodedChar);
      }

      return chunks.join("");
   }


   export function Decode(value: string) {
      const chunks: string[] = [];
      for (const char of value) {
         const codePoint = char.codePointAt(0) as number;

         if (codePoint < puaBase || codePoint > puaMax) {
            chunks.push(char);
            continue;
         }

         const mappedCodePoint = codePointMap.get(codePoint) as number
         const decodedChar = String.fromCodePoint(mappedCodePoint)
         chunks.push(decodedChar);
      }

      return chunks.join("");
   }

